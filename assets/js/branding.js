(() => {
  const CFG = window.DREAM_EVENTS_CONFIG;
  if (CFG) CFG.APP_NAME = 'Thambili Events Finance';

  document.title = 'Thambili Events Finance';

  const exactMap = new Map([
    ['DREAM EVENTS', 'THAMBILI EVENTS'],
    ['Dream Events', 'Thambili Events'],
    ['Dream Events Finance', 'Thambili Events Finance'],
    ['Dream Events Cash', 'Thambili Events Cash'],
    ['Dream Events Bank', 'Thambili Events Bank'],
    ['Connected to Dream Events backend', 'Connected to Thambili Events backend']
  ]);

  function brandText(value) {
    let text = String(value ?? '');
    text = text.replaceAll('Dream Events Finance', 'Thambili Events Finance');
    text = text.replaceAll('Connected to Dream Events backend', 'Connected to Thambili Events backend');
    text = text.replaceAll('Dream Events Cash', 'Thambili Events Cash');
    text = text.replaceAll('Dream Events Bank', 'Thambili Events Bank');
    text = text.replaceAll('Dream Events Google Drive', 'Thambili Events Google Drive');
    text = text.replaceAll('Authorized by Dream Events', 'Authorized by Thambili Events');
    text = text.replaceAll('Thank you for choosing Dream Events.', 'Thank you for choosing Thambili Events.');
    text = text.replaceAll('Dream Events ·', 'Thambili Events ·');
    if (text.trim() === 'DREAM EVENTS') text = text.replace('DREAM EVENTS', 'THAMBILI EVENTS');
    if (text.trim() === 'Dream Events') text = text.replace('Dream Events', 'Thambili Events');
    return text;
  }

  function brandElement(root) {
    if (!root || root.nodeType !== 1) return;

    // App.js writes this eyebrow on each navigation.
    root.querySelectorAll?.('#pageEyebrow').forEach(el => {
      if (el.textContent.trim() === 'DREAM EVENTS') el.textContent = 'THAMBILI EVENTS';
    });

    // Printed-document logo generated by app.js.
    root.querySelectorAll?.('.quotation-logo').forEach(el => {
      if (el.textContent.trim() === 'DE') el.textContent = 'TE';
    });

    // Customer-facing document brand text and operational labels.
    const selectors = [
      '.quotation-brand h2',
      '.quotation-authorized span',
      '.quotation-authorized strong',
      '.quotation-footer span',
      '#demoHint',
      '#expenseForm option',
      '#expenseForm small'
    ];
    root.querySelectorAll?.(selectors.join(',')).forEach(el => {
      const next = brandText(el.textContent);
      if (next !== el.textContent) el.textContent = next;
    });

    // Admin company-name field can still contain the old database value
    // until applyThambiliBranding() has been run once.
    root.querySelectorAll?.('input[name="COMPANY_NAME"]').forEach(input => {
      if (input.value.trim() === 'Dream Events') input.value = 'Thambili Events';
    });
  }

  // Install before app.js renders dynamic screens.
  const observer = new MutationObserver(records => {
    for (const record of records) {
      for (const node of record.addedNodes) {
        if (node.nodeType === 1) {
          brandElement(node);
          if (node.matches?.('#pageEyebrow') && node.textContent.trim() === 'DREAM EVENTS') {
            node.textContent = 'THAMBILI EVENTS';
          }
        }
      }
      if (record.type === 'characterData') {
        const parent = record.target.parentElement;
        if (parent?.id === 'pageEyebrow' && parent.textContent.trim() === 'DREAM EVENTS') {
          parent.textContent = 'THAMBILI EVENTS';
        }
      }
    }
  });
  observer.observe(document.documentElement, {subtree:true, childList:true, characterData:true});

  brandElement(document);

  // app.js creates a separate browser window for quotation/invoice/receipt printing.
  // Patch document.write in that new window so customer-facing PDFs use the new brand
  // without changing the stable production app.js.
  const nativeOpen = window.open.bind(window);
  window.open = function(...args) {
    const child = nativeOpen(...args);
    if (!child) return child;

    try {
      const nativeWrite = child.document.write.bind(child.document);
      child.document.write = function(html) {
        let branded = String(html ?? '')
          .replaceAll('Dream Events Finance', 'Thambili Events Finance')
          .replaceAll('Authorized by Dream Events', 'Authorized by Thambili Events')
          .replaceAll('Thank you for choosing Dream Events.', 'Thank you for choosing Thambili Events.')
          .replaceAll('Dream Events ·', 'Thambili Events ·')
          .replaceAll('<h2>Dream Events</h2>', '<h2>Thambili Events</h2>')
          .replaceAll('class="quotation-logo">DE<', 'class="quotation-logo">TE<')
          // Old quotation gold palette -> Thambili orange palette.
          .replaceAll('#b88a34', '#ff4400')
          .replaceAll('#9a6d19', '#d63800')
          .replaceAll('#f6f1e8', '#fff1eb')
          .replaceAll('#e7dfd1', '#f0d8cf')
          .replaceAll('#eee8de', '#f4e5df')
          .replaceAll('#ddd4c4', '#e8d7d0');
        return nativeWrite(branded);
      };
    } catch (_) {}
    return child;
  };
})();